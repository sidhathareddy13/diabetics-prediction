from datetime import datetime
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from backend.auth import category_color

BASE_DIR = Path(__file__).resolve().parent.parent


def build_pdf_report(title, sections):
    pdf_path = BASE_DIR / 'tmp_report.pdf'
    doc = SimpleDocTemplate(str(pdf_path), pagesize=letter)
    styles = getSampleStyleSheet()
    story = [Paragraph(title, styles['Title'])]
    for heading, content in sections:
        story.append(Spacer(1, 0.2 * inch))
        story.append(Paragraph(heading, styles['Heading2']))
        story.append(Paragraph(content, styles['BodyText']))
    doc.build(story)
    return pdf_path


def build_individual_report_pdf(user, prediction):
    """Build a professional individual diabetes risk assessment report."""
    pdf_path = BASE_DIR / 'tmp_individual_report.pdf'
    doc = SimpleDocTemplate(str(pdf_path), pagesize=letter, topMargin=0.5*inch, bottomMargin=0.5*inch)
    styles = getSampleStyleSheet()
    story = []

    title_style = styles['Title']
    title_style.fontSize = 24
    title_style.textColor = colors.HexColor('#5437c5')
    story.append(Paragraph('Diabetes Report', title_style))

    subtitle_style = styles['Heading2']
    subtitle_style.fontSize = 16
    subtitle_style.textColor = colors.HexColor('#667085')
    story.append(Paragraph('Diabetes Risk Assessment', subtitle_style))
    story.append(Spacer(1, 0.3 * inch))

    story.append(Paragraph('PATIENT DETAILS', styles['Heading3']))
    patient_details = [
        ['Patient Name', user.get('full_name', 'N/A')],
        ['Age / Gender', f"{prediction['age']} Years / {user.get('gender', 'N/A')}"],
        ['Email', user.get('email', 'N/A')],
        ['Collection Date', prediction['created_at']],
        ['Report Type', 'Individual Report'],
    ]
    patient_table = Table(patient_details, colWidths=[2.5*inch, 3.5*inch])
    patient_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#f3efff')),
        ('TEXTCOLOR', (0, 0), (-1, -1), colors.HexColor('#1f2a44')),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 10),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 12),
        ('TOPPADDING', (0, 0), (-1, -1), 10),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e5e7eb')),
    ]))
    story.append(patient_table)
    story.append(Spacer(1, 0.3 * inch))

    story.append(Paragraph('PATIENT HEALTH PARAMETERS', styles['Heading3']))
    risk_color = category_color(prediction['risk_category'])

    health_data = [
        ['Parameter', 'Value'],
        ['Glucose (mg/dL)', str(prediction['glucose'])],
        ['Blood Pressure (mmHg)', str(prediction['blood_pressure'])],
        ['BMI (kg/m²)', str(prediction['bmi'])],
        ['Age (Years)', str(prediction['age'])],
        ['Insulin (µU/mL)', str(prediction['insulin'])],
        ['Predicted Diabetes Risk', f"{prediction['risk_score']:.1f}%"],
        ['Risk Level', prediction['risk_category']],
    ]

    health_table = Table(health_data, colWidths=[3*inch, 3*inch])
    health_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#f3efff')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#1f2a44')),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 10),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 10),
        ('TOPPADDING', (0, 0), (-1, -1), 10),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e5e7eb')),
        ('BACKGROUND', (0, -2), (-1, -1), colors.HexColor(risk_color)),
        ('TEXTCOLOR', (0, -2), (-1, -1), colors.white),
        ('FONTNAME', (0, -2), (-1, -1), 'Helvetica-Bold'),
    ]))
    story.append(health_table)
    story.append(Spacer(1, 0.3 * inch))

    story.append(Paragraph('IMPORTANT DISCLAIMER', styles['Heading3']))
    disclaimer_text = (
        'This report is generated by an AI/ML model for educational and risk-screening purposes only. '
        'It does not diagnose diabetes and should not be used as a substitute for professional medical advice, '
        'diagnosis, or treatment. Always consult a qualified healthcare professional for medical concerns.'
    )
    story.append(Paragraph(disclaimer_text, styles['BodyText']))
    story.append(Spacer(1, 0.15 * inch))

    report_generated_time = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    story.append(Paragraph(f'Report generated on: {report_generated_time}', styles['Normal']))

    doc.build(story)
    return pdf_path


def build_overall_report_pdf(user, predictions):
    """Build a professional overall diabetes risk assessment report."""
    pdf_path = BASE_DIR / 'tmp_overall_report.pdf'
    doc = SimpleDocTemplate(str(pdf_path), pagesize=letter, topMargin=0.5*inch, bottomMargin=0.5*inch)
    styles = getSampleStyleSheet()
    story = []

    title_style = styles['Title']
    title_style.fontSize = 24
    title_style.textColor = colors.HexColor('#5437c5')
    story.append(Paragraph('Diabetes Report', title_style))

    subtitle_style = styles['Heading2']
    subtitle_style.fontSize = 16
    subtitle_style.textColor = colors.HexColor('#667085')
    story.append(Paragraph('Overall Assessment Summary (All Reports)', subtitle_style))
    story.append(Spacer(1, 0.3 * inch))

    story.append(Paragraph('PATIENT DETAILS', styles['Heading3']))

    if predictions:
        from_date = min(p['created_at'] for p in predictions).split()[0]
        to_date = max(p['created_at'] for p in predictions).split()[0]
    else:
        from_date = to_date = 'N/A'

    patient_details = [
        ['Patient Name', user.get('full_name', 'N/A')],
        ['Age / Gender', f"{predictions[0]['age'] if predictions else 'N/A'} Years / {user.get('gender', 'N/A')}"],
        ['Email', user.get('email', 'N/A')],
        ['Collection Date (From)', from_date],
        ['Collection Date (To)', to_date],
        ['Report Type', 'Overall Summary Report'],
        ['Total Assessments', str(len(predictions))],
    ]

    patient_table = Table(patient_details, colWidths=[2.5*inch, 3.5*inch])
    patient_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#f3efff')),
        ('TEXTCOLOR', (0, 0), (-1, -1), colors.HexColor('#1f2a44')),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 10),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 10),
        ('TOPPADDING', (0, 0), (-1, -1), 10),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e5e7eb')),
    ]))
    story.append(patient_table)
    story.append(Spacer(1, 0.3 * inch))

    if predictions:
        story.append(Paragraph('OVERALL HEALTH SUMMARY (ALL REPORTS)', styles['Heading3']))

        glucose_values = [p['glucose'] for p in predictions]
        bp_values = [p['blood_pressure'] for p in predictions]
        bmi_values = [p['bmi'] for p in predictions]
        age_values = [p['age'] for p in predictions]
        insulin_values = [p['insulin'] for p in predictions]

        def calculate_trend(values):
            if len(values) < 2:
                return 'Stable / Insufficient data'
            recent_half = values[:len(values)//2]
            older_half = values[len(values)//2:]
            avg_recent = sum(recent_half) / len(recent_half) if recent_half else 0
            avg_older = sum(older_half) / len(older_half) if older_half else 0
            if avg_recent > avg_older * 1.05:
                return 'Increasing'
            elif avg_recent < avg_older * 0.95:
                return 'Decreasing'
            return 'Stable'

        summary_data = [
            ['Parameter', 'Average Value', 'Minimum Value', 'Maximum Value', 'Latest Value', 'Trend'],
            ['Glucose (mg/dL)', f"{sum(glucose_values)/len(glucose_values):.1f}", f"{min(glucose_values):.1f}", f"{max(glucose_values):.1f}", f"{glucose_values[0]:.1f}", calculate_trend(glucose_values)],
            ['Blood Pressure (mmHg)', f"{sum(bp_values)/len(bp_values):.1f}", f"{min(bp_values):.1f}", f"{max(bp_values):.1f}", f"{bp_values[0]:.1f}", calculate_trend(bp_values)],
            ['BMI (kg/m²)', f"{sum(bmi_values)/len(bmi_values):.1f}", f"{min(bmi_values):.1f}", f"{max(bmi_values):.1f}", f"{bmi_values[0]:.1f}", calculate_trend(bmi_values)],
            ['Age (Years)', f"{sum(age_values)//len(age_values)}", f"{min(age_values)}", f"{max(age_values)}", f"{age_values[0]}", 'N/A'],
            ['Insulin (µU/mL)', f"{sum(insulin_values)/len(insulin_values):.1f}", f"{min(insulin_values):.1f}", f"{max(insulin_values):.1f}", f"{insulin_values[0]:.1f}", calculate_trend(insulin_values)],
        ]

        summary_table = Table(summary_data, colWidths=[1.2*inch, 1*inch, 1*inch, 1*inch, 1*inch, 1.3*inch])
        summary_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#f3efff')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#1f2a44')),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 8),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
            ('TOPPADDING', (0, 0), (-1, -1), 8),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e5e7eb')),
        ]))
        story.append(summary_table)
        story.append(Spacer(1, 0.25 * inch))

        story.append(Paragraph('ALL ASSESSMENTS SUMMARY', styles['Heading3']))

        assess_data = [['#', 'Date & Time', 'Glucose', 'BP', 'BMI', 'Age', 'Insulin', 'Risk %', 'Risk Level']]
        for idx, pred in enumerate(predictions, 1):
            assess_data.append([
                str(idx),
                pred['created_at'],
                f"{pred['glucose']:.1f}",
                f"{pred['blood_pressure']:.1f}",
                f"{pred['bmi']:.1f}",
                str(pred['age']),
                f"{pred['insulin']:.1f}",
                f"{pred['risk_score']:.1f}%",
                pred['risk_category'],
            ])

        assess_table = Table(assess_data, colWidths=[0.4*inch, 1.3*inch, 0.7*inch, 0.7*inch, 0.6*inch, 0.5*inch, 0.7*inch, 0.7*inch, 1*inch])
        assess_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#f3efff')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#1f2a44')),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 7),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e5e7eb')),
        ]))
        story.append(assess_table)
        story.append(Spacer(1, 0.2 * inch))

    story.append(Paragraph('IMPORTANT DISCLAIMER', styles['Heading3']))
    disclaimer_text = (
        'This report is generated by an AI/ML model for educational and risk-screening purposes only. '
        'It does not diagnose diabetes and should not be used as a substitute for professional medical advice, '
        'diagnosis, or treatment. Always consult a qualified healthcare professional for medical concerns.'
    )
    story.append(Paragraph(disclaimer_text, styles['BodyText']))
    story.append(Spacer(1, 0.1 * inch))

    report_generated_time = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    story.append(Paragraph(f'Report generated on: {report_generated_time}', styles['Normal']))

    doc.build(story)
    return pdf_path
